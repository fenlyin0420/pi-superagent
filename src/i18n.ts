const DICTIONARIES: Record<Locale, Record<MessageKey, string>> = { en, zh };

let locale: Locale = "en";

export type MessageParams = Readonly<Record<string, string | number>>;

export function setLocale(next: Locale): void {
	locale = next;
}

export function getLocale(): Locale {
	return locale;
}

/** The message for `key` in the current locale, with `{name}` placeholders filled in. */
export function t(key: MessageKey, params?: MessageParams): string {
	return fill(DICTIONARIES[locale][key], params);
}

/** A failure's code, when the dictionary knows it; otherwise the failure's own sentence. */
export function errorText(failure: {
	readonly error: string;
	readonly code?: string;
	readonly values?: Record<string, string>;
}): string {
	const code = failure.code;
	if (code === undefined) return failure.error;
	const key = `error.${code}`;
	if (!isMessageKey(key)) return failure.error;
	return t(key, failure.values ?? {});
}

function isMessageKey(key: string): key is MessageKey {
	return key in en;
}

function fill(template: string, params: MessageParams = {}): string {
	return template.replace(/\{(\w+)\}/g, (match, name: string) => {
		const value = params[name];
		return value === undefined ? match : String(value);
	});
}
